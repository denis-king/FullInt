#!/usr/bin/env python3
# Generates FullInt.Asm/Sources/arm32/NttNeon.s: the number-theoretic transform kernels for ARMv7
# NEON (the contracts of x64 NttAvx2.asm, the algorithms of arm64/NttNeon.s). ARMv7 NEON names a
# 128-bit register q<n> and its halves d<2n>, d<2n+1>; the long multiplies (vmull) and the
# narrowing (vshrn) take the halves - this script spells the halves out, so the macros below are
# Python functions. Run it after a change and commit both:
#   python FullInt.Asm/build/gen-ntt-arm32.py
import os

out = []


def emit(s=''):
    out.append(s)


def lo(q): return f'd{2 * q}'
def hi(q): return f'd{2 * q + 1}'


P, P2 = 15, 14   # q15 = p, q14 = 2p


def himul(r, a, b, t0, t1):
    """q<r> = the high 32 bits of the four lane products a·b (t0, t1 scratch; r distinct from them)"""
    emit(f'    vmull.u32 q{t0}, {lo(a)}, {lo(b)}')
    emit(f'    vmull.u32 q{t1}, {hi(a)}, {hi(b)}')
    emit(f'    vshrn.i64 {lo(r)}, q{t0}, #32')
    emit(f'    vshrn.i64 {hi(r)}, q{t1}, #32')


def muls(r, a, w, wq, t0, t1, t2):
    """r = a·w mod p in [0, 2p), w in Shoup's form (wq = floor(w·2^32 / p)); r distinct from a, t*"""
    himul(t2, a, wq, t0, t1)                       # q = hi(a·wq)
    emit(f'    vmul.i32 q{r}, q{a}, q{w}')
    emit(f'    vmls.i32 q{r}, q{t2}, q{P}')         # a·w - q·p


def mulw(r, a, w, wq, t0, t1, t2, t3):
    """r = a·w·2^-32 mod p in [0, 2p) (Montgomery, wq = w·p^-1 mod 2^32); r may be a / w"""
    himul(t2, a, w, t0, t1)                        # hi(a·w)
    emit(f'    vmul.i32 q{t3}, q{a}, q{wq}')       # m
    himul(t3, t3, P, t0, t1)                       # hi(m·p) over m (both halves read first)
    emit(f'    vsub.i32 q{r}, q{t2}, q{t3}')
    emit(f'    vadd.i32 q{r}, q{r}, q{P}')


def red(v, t):
    """v = min(v, v - 2p): [0, 4p) -> [0, 2p)"""
    emit(f'    vsub.i32 q{t}, q{v}, q{P2}')
    emit(f'    vmin.u32 q{v}, q{v}, q{t}')


def red_p(v, t):
    """[0, 2p) -> [0, p)"""
    emit(f'    vsub.i32 q{t}, q{v}, q{P}')
    emit(f'    vmin.u32 q{v}, q{v}, q{t}')


def dif_bfly(u, v, w, wq, s, d, t, m0, m1, m2):
    """(u, v) -> (u + v, (u - v)·w)"""
    emit(f'    vadd.i32 q{s}, q{u}, q{v}')
    emit(f'    vsub.i32 q{d}, q{u}, q{v}')
    emit(f'    vadd.i32 q{d}, q{d}, q{P2}')        # u - v + 2p in (0, 4p)
    red(s, t)
    muls(v, d, w, wq, m0, m1, m2)
    emit(f'    vmov q{u}, q{s}')


def dit_bfly(u, v, w, wq, s, d, t, m0, m1, m2):
    """(u, v) -> (u + v·w, u - v·w)"""
    muls(s, v, w, wq, m0, m1, m2)                  # v·w in [0, 2p)
    emit(f'    vadd.i32 q{d}, q{u}, q{s}')
    emit(f'    vsub.i32 q{v}, q{u}, q{s}')
    emit(f'    vadd.i32 q{v}, q{v}, q{P2}')
    red(d, t)
    red(v, t)
    emit(f'    vmov q{u}, q{d}')


def bfly1(u, v, s, t):
    """the twiddle 1: (u, v) -> (u + v, u - v)"""
    emit(f'    vadd.i32 q{s}, q{u}, q{v}')
    emit(f'    vsub.i32 q{v}, q{u}, q{v}')
    emit(f'    vadd.i32 q{v}, q{v}, q{P2}')
    red(s, t)
    red(v, t)
    emit(f'    vmov q{u}, q{s}')


def setup_p(reg):
    emit(f'    vdup.32 q{P}, {reg}')
    emit(f'    vadd.i32 q{P2}, q{P}, q{P}')


# butterfly scratch: q4-q7 (callee-saved: d8-d15 pushed by every entry), q12, q13
S1 = (4, 5, 6, 7, 12, 13)

HEADER = r'''// =============================================================================
//  GENERATED by FullInt.Asm/build/gen-ntt-arm32.py - edit the script, not this file.
//
//  Number-theoretic transform kernels (ARMv7 NEON): the contracts of x64 NttAvx2.asm, the
//  algorithms of arm64/NttNeon.s (its header has the scheme): three primes p < 2^30, the values
//  lazy in [0, 2p); the radix-2 twiddles in Shoup's form (w, wq = floor(w·2^32 / p): five
//  instructions a product), the pointwise product, the scaling and the radix-3 level in
//  Montgomery's (wq = w·p^-1 mod 2^32). Four lanes of 32 bits; the high halves of the products
//  by vmull.u32 (two lanes) and vshrn #32. The load and the CRT are scalar.
//  NEON is optional on ARMv7: the callers check for it (HWCAP_NEON) before taking these.
//
//  AAPCS: a 64-bit argument in an even / odd register pair or an 8-byte-aligned stack slot; d8-d15
//  (q4-q7) kept for the caller. q15 = p, q14 = 2p.
//    void Fullint64NttDif1WIN_neon(uint32* x, int64 L, int64 h, const uint32* W, const uint32* Wq, uint32 p)
//    void Fullint64NttDif2WIN_neon(... same ...)       levels h, h/2
//    void Fullint64NttDif3WIN_neon(uint32* x, int64 L, const uint32* W, const uint32* Wq, uint32 p)
//    void Fullint64NttDit1WIN_neon / Dit2 (levels h/2, h) / Dit3: the same, the inverse tables
//    void Fullint64NttPointWIN_neon(uint32* x, const uint32* y, int64 n, uint32 p, uint32 pinv)
//    void Fullint64NttScaleWIN_neon(uint32* x, int64 n, uint32 p, uint32 c, uint32 cq)
//    void Fullint64NttR3DifWIN_neon(uint32* x, int64 M, const uint32* k, uint32 p) / R3Dit
//    void Fullint64NttLoadWIN_neon(const uint64* a, int64 la, uint32* x, int64 L, uint32 p)
//    uint64 Fullint64NttCrtWIN_neon(const uint32* x0, const uint32* x1, const uint32* x2, int64 nd,
//                                   uint64* r, int64 len, const uint64* k)
// =============================================================================

    .include "abi.inc"
    .fpu neon
'''

emit(HEADER)

# the stack arguments: after push {r4-r11, lr} (36 bytes) and vpush {d8-d15} (64): sp + 100
SA = 100


def prologue():
    emit('    push {r4-r11, lr}')
    emit('    vpush {d8-d15}')


def epilogue():
    emit('    vpop {d8-d15}')
    emit('    pop {r4-r11, pc}')


def level(dif, tag):
    """one level h >= 8 over x[0 .. L): r0 x, r2 L, r4 h, r1 W, r3 Wq. Two vectors of j a step."""
    emit(f'    add r5, r1, r4, lsl #2          // &W[h]')
    emit(f'    add r6, r3, r4, lsl #2          // &Wq[h]')
    emit(f'    mov r7, r0                      // the block')
    emit(f'    add r8, r0, r2, lsl #2          // the end')
    emit(f'{tag}1:')
    emit(f'    mov r9, r7                      // x[b + j]')
    emit(f'    add r10, r7, r4, lsl #2         // x[b + j + h]')
    emit(f'    mov r11, r5')
    emit(f'    mov r12, r6')
    emit(f'    mov lr, r4')
    emit(f'{tag}2:')
    emit(f'    vld1.32 {{d0-d3}}, [r9]           // u: j .. j + 7')
    emit(f'    vld1.32 {{d4-d7}}, [r10]          // v')
    emit(f'    vld1.32 {{d16-d19}}, [r11]!       // W')
    emit(f'    vld1.32 {{d20-d23}}, [r12]!       // Wq')
    if dif:
        dif_bfly(0, 2, 8, 10, *S1)
        dif_bfly(1, 3, 9, 11, *S1)
    else:
        dit_bfly(0, 2, 8, 10, *S1)
        dit_bfly(1, 3, 9, 11, *S1)
    emit(f'    vst1.32 {{d0-d3}}, [r9]!')
    emit(f'    vst1.32 {{d4-d7}}, [r10]!')
    emit(f'    subs lr, lr, #8')
    emit(f'    bne {tag}2')
    emit(f'    add r7, r7, r4, lsl #3          // the next block: 2h values on')
    emit(f'    cmp r7, r8')
    emit(f'    blo {tag}1')


def entry(name):
    emit()
    emit(f'ENTRY {name}')


def end(name):
    emit(f'END {name}')


def level_entry(name, dif, double, tag):
    # r0 x, r2 L (r2:r3), stack: h (+0, 8 bytes), W (+8), Wq (+12), p (+16)
    entry(name)
    prologue()
    emit(f'    ldr r4, [sp, #{SA}]             // h')
    emit(f'    ldr r1, [sp, #{SA + 8}]         // W')
    emit(f'    ldr r3, [sp, #{SA + 12}]        // Wq')
    emit(f'    ldr r5, [sp, #{SA + 16}]')
    setup_p('r5')
    if not double:
        level(dif, tag + 'a')
    elif dif:
        level(dif, tag + 'a')
        emit('    lsr r4, r4, #1')
        level(dif, tag + 'b')
    else:
        emit('    lsr r4, r4, #1')
        level(dif, tag + 'a')
        emit('    lsl r4, r4, #1')
        level(dif, tag + 'b')
    epilogue()
    end(name)


def last3(name, dif, tag):
    # r0 x, r2 L; stack: W (+0), Wq (+4), p (+8). 16 values a step in q0-q3.
    entry(name)
    prologue()
    emit(f'    ldr r1, [sp, #{SA}]             // W')
    emit(f'    ldr r3, [sp, #{SA + 4}]         // Wq')
    emit(f'    ldr r5, [sp, #{SA + 8}]')
    setup_p('r5')
    emit('    add r6, r1, #16')
    emit('    vld1.32 {d16-d17}, [r6]           // W[4..7]')
    emit('    add r6, r3, #16')
    emit('    vld1.32 {d20-d21}, [r6]           // Wq[4..7]')
    emit('    add r6, r1, #8')
    emit('    vld1.32 {d18}, [r6]               // W[2], W[3], twice')
    emit('    vmov d19, d18')
    emit('    add r6, r3, #8')
    emit('    vld1.32 {d22}, [r6]')
    emit('    vmov d23, d22')
    emit(f'{tag}3:')
    emit('    vld1.32 {d0-d3}, [r0]!')
    emit('    vld1.32 {d4-d7}, [r0]')
    emit('    sub r0, r0, #32')
    if dif:
        dif_bfly(0, 1, 8, 10, *S1)                 # level 4
        dif_bfly(2, 3, 8, 10, *S1)
        emit('    vswp d1, d2                       // U, V: the 64-bit halves')
        emit('    vswp d5, d6')
        dif_bfly(0, 1, 9, 11, *S1)                 # level 2
        dif_bfly(2, 3, 9, 11, *S1)
        emit('    vuzp.32 q0, q1                    // P, Q: the lanes')
        emit('    vuzp.32 q2, q3')
        bfly1(0, 1, 4, 6)                          # level 1
        bfly1(2, 3, 4, 6)
    else:
        bfly1(0, 1, 4, 6)                          # level 1 on P, Q
        bfly1(2, 3, 4, 6)
        emit('    vzip.32 q0, q1                    // U, V')
        emit('    vzip.32 q2, q3')
        dit_bfly(0, 1, 9, 11, *S1)                 # level 2
        dit_bfly(2, 3, 9, 11, *S1)
        emit('    vswp d1, d2                       // A, B')
        emit('    vswp d5, d6')
        dit_bfly(0, 1, 8, 10, *S1)                 # level 4
        dit_bfly(2, 3, 8, 10, *S1)
    emit('    vst1.32 {d0-d3}, [r0]!')
    emit('    vst1.32 {d4-d7}, [r0]!')
    emit('    subs r2, r2, #16')
    emit(f'    bne {tag}3')
    epilogue()
    end(name)


level_entry('Fullint64NttDif1WIN_neon', True, False, '.Ldif1')
level_entry('Fullint64NttDif2WIN_neon', True, True, '.Ldif2')
last3('Fullint64NttDif3WIN_neon', True, '.Ldif3')
level_entry('Fullint64NttDit1WIN_neon', False, False, '.Ldit1')
level_entry('Fullint64NttDit2WIN_neon', False, True, '.Ldit2')
last3('Fullint64NttDit3WIN_neon', False, '.Ldit3')

# x = x·y·2^-32 in [0, 2p): r0 x, r1 y, r2 n (r2:r3), stack: p (+0), pinv (+4)
entry('Fullint64NttPointWIN_neon')
prologue()
emit(f'    ldr r4, [sp, #{SA}]')
emit(f'    ldr r5, [sp, #{SA + 4}]')
setup_p('r4')
emit('    vdup.32 q13, r5                   // p^-1')
emit('.Lpoint:')
emit('    vld1.32 {d0-d1}, [r0]')
emit('    vld1.32 {d2-d3}, [r1]!')
emit('    vmul.i32 q3, q1, q13              // y·p^-1')
mulw(2, 0, 1, 3, 8, 9, 10, 11)
emit('    vst1.32 {d4-d5}, [r0]!')
emit('    subs r2, r2, #4')
emit('    bne .Lpoint')
epilogue()
end('Fullint64NttPointWIN_neon')

# x = x·c·2^-32 in [0, p): r0 x, r2 n (r2:r3), stack: p (+0), c (+4), cq (+8)
entry('Fullint64NttScaleWIN_neon')
prologue()
emit(f'    ldr r4, [sp, #{SA}]')
emit(f'    ldr r5, [sp, #{SA + 4}]')
emit(f'    ldr r6, [sp, #{SA + 8}]')
setup_p('r4')
emit('    vdup.32 q1, r5')
emit('    vdup.32 q3, r6')
emit('.Lscale:')
emit('    vld1.32 {d0-d1}, [r0]')
mulw(2, 0, 1, 3, 8, 9, 10, 11)
red_p(2, 12)
emit('    vst1.32 {d4-d5}, [r0]!')
emit('    subs r2, r2, #4')
emit('    bne .Lscale')
epilogue()
end('Fullint64NttScaleWIN_neon')

# The radix-3 level of a transform of N = 3M values, four j a step (arm64/NttNeon.s). k
# (Montgomery form, 32-bit entries): [0..7] w^0..7, [8..15] w^0,2,..,14, [16..23] w^8, [24..31]
# its q, [48..55] ω, [56..63] its q, [64..71] p^-1. r0 x, r2 M (r2:r3), stack: k (+0), p (+4).
# q13 p^-1, q12 w^j, q11 w^2j; ω, ω's q, w^8, its q loaded from k a step; w^4 and its q on the
# stack (32 bytes below the saved registers). r1 = k, r4 = x + M, r5 = x + 2M.


def r3_setup():
    prologue()
    emit('    sub sp, sp, #32')
    emit(f'    ldr r1, [sp, #{SA + 32}]        // k')
    emit(f'    ldr r6, [sp, #{SA + 36}]        // p')
    setup_p('r6')
    emit('    add r6, r1, #256')
    emit('    vld1.32 {d26-d27}, [r6]           // p^-1')
    emit('    vld1.32 {d24-d25}, [r1]           // w^0..3')
    emit('    add r6, r1, #32')
    emit('    vld1.32 {d22-d23}, [r6]           // w^0,2,4,6')
    emit('    ldr r6, [r1, #16]                 // w^4, broadcast; its q')
    emit('    vdup.32 q0, r6')
    emit('    vmul.i32 q1, q0, q13')
    emit('    vst1.32 {d0-d3}, [sp]')
    emit('    add r4, r0, r2, lsl #2            // x + M')
    emit('    add r5, r4, r2, lsl #2            // x + 2M')


def r3_epilogue():
    emit('    add sp, sp, #32')
    epilogue()


def r3_step():
    """the twiddles four j on: w^j·w^4, w^2j·w^8, below p"""
    emit('    vld1.32 {d16-d19}, [sp]           // w^4, its q')
    mulw(3, 12, 8, 9, 0, 1, 2, 10)
    red_p(3, 6)
    emit('    vmov q12, q3')
    emit('    add r6, r1, #64')
    emit('    vld1.32 {d16-d17}, [r6]           // w^8')
    emit('    add r6, r1, #96')
    emit('    vld1.32 {d18-d19}, [r6]           // its q')
    mulw(3, 11, 8, 9, 0, 1, 2, 10)
    red_p(3, 6)
    emit('    vmov q11, q3')


def load_omega():
    emit('    add r6, r1, #192')
    emit('    vld1.32 {d16-d17}, [r6]           // ω')
    emit('    add r6, r1, #224')
    emit('    vld1.32 {d18-d19}, [r6]           // its q')


# y0 = x0 + x1 + x2, y1 = (x0 - x2 + ω·(x1 - x2))·w^j, y2 = (x0 - x1 - ω·(x1 - x2))·w^2j
entry('Fullint64NttR3DifWIN_neon')
r3_setup()
emit('.Lr3dif:')
emit('    vld1.32 {d0-d1}, [r0]')
emit('    vld1.32 {d2-d3}, [r4]')
emit('    vld1.32 {d4-d5}, [r5]')
emit('    vsub.i32 q3, q1, q2')
emit(f'    vadd.i32 q3, q3, q{P2}')
load_omega()
mulw(4, 3, 8, 9, 5, 6, 7, 10)                  # u = ω·(x1 - x2)
emit('    vadd.i32 q5, q0, q1                // y0')
red(5, 6)
emit('    vadd.i32 q5, q5, q2')
red(5, 6)
emit('    vsub.i32 q3, q0, q2                // y1')
emit(f'    vadd.i32 q3, q3, q{P2}')
red(3, 6)
emit('    vadd.i32 q3, q3, q4')
emit('    vmul.i32 q9, q12, q13')
mulw(7, 3, 12, 9, 6, 8, 10, 2)                 # (x2 free)
emit('    vsub.i32 q3, q0, q1                // y2')
emit(f'    vadd.i32 q3, q3, q{P2}')
red(3, 6)
emit('    vsub.i32 q3, q3, q4')
emit(f'    vadd.i32 q3, q3, q{P2}')
emit('    vmul.i32 q9, q11, q13')
mulw(1, 3, 11, 9, 0, 2, 6, 8)                  # (x0, x1 free)
emit('    vst1.32 {d10-d11}, [r0]!')
emit('    vst1.32 {d14-d15}, [r4]!')
emit('    vst1.32 {d2-d3}, [r5]!')
r3_step()
emit('    subs r2, r2, #4')
emit('    bne .Lr3dif')
r3_epilogue()
end('Fullint64NttR3DifWIN_neon')

# y1' = y1·w^j, y2' = y2·w^2j (w and ω inverted); x0 = y0 + y1' + y2',
# x1 = y0 - y2' + ω·(y1' - y2'), x2 = y0 - y1' - ω·(y1' - y2')
entry('Fullint64NttR3DitWIN_neon')
r3_setup()
emit('.Lr3dit:')
emit('    vld1.32 {d0-d1}, [r0]')
emit('    vld1.32 {d2-d3}, [r4]')
emit('    vld1.32 {d4-d5}, [r5]')
emit('    vmul.i32 q9, q12, q13')
mulw(3, 1, 12, 9, 6, 7, 8, 10)                 # y1'
emit('    vmul.i32 q9, q11, q13')
mulw(7, 2, 11, 9, 6, 8, 10, 1)                 # y2' (x1 free)
emit('    vsub.i32 q4, q3, q7')
emit(f'    vadd.i32 q4, q4, q{P2}')
load_omega()
mulw(2, 4, 8, 9, 1, 6, 10, 5)                  # u = ω·(y1' - y2') (x2 free)
emit('    vadd.i32 q5, q0, q3                // x0')
red(5, 6)
emit('    vadd.i32 q5, q5, q7')
red(5, 6)
emit('    vsub.i32 q4, q0, q7                // x1')
emit(f'    vadd.i32 q4, q4, q{P2}')
red(4, 6)
emit('    vadd.i32 q4, q4, q2')
red(4, 6)
emit('    vsub.i32 q1, q0, q3                // x2')
emit(f'    vadd.i32 q1, q1, q{P2}')
red(1, 6)
emit('    vsub.i32 q1, q1, q2')
emit(f'    vadd.i32 q1, q1, q{P2}')
red(1, 6)
emit('    vst1.32 {d10-d11}, [r0]!')
emit('    vst1.32 {d8-d9}, [r4]!')
emit('    vst1.32 {d2-d3}, [r5]!')
r3_step()
emit('    subs r2, r2, #4')
emit('    bne .Lr3dit')
r3_epilogue()
end('Fullint64NttR3DitWIN_neon')

emit(r'''
// -----------------------------------------------------------------------------
// The load: big-endian words -> little-endian 32-bit digits in [0, 2p) (a digit < 2^32 < 5p:
// minus 2p twice at most), then zeros up to L. r0 a, r2 la (r2:r3); stack: x (+0), L (+8), p (+16).
ENTRY Fullint64NttLoadWIN_neon
    push {r4-r8, lr}
    ldr r4, [sp, #24]           // x
    ldr r5, [sp, #32]           // L
    ldr r6, [sp, #40]           // p
    lsl r6, r6, #1              // 2p
    add r0, r0, r2, lsl #3      // past a's lowest word
    sub r5, r5, r2, lsl #1      // the zeros after
    teq r2, #0
    beq 2f
1:  ldmdb r0!, {r7, r8}
    cmp r7, r6
    subhs r7, r7, r6
    cmp r7, r6
    subhs r7, r7, r6
    cmp r8, r6
    subhs r8, r8, r6
    cmp r8, r6
    subhs r8, r8, r6
    stmia r4!, {r7, r8}
    subs r2, r2, #1
    bne 1b
2:  mov r7, #0
    teq r5, #0
    beq 4f
3:  str r7, [r4], #4
    subs r5, r5, #1
    bne 3b
4:  pop {r4-r8, pc}
END Fullint64NttLoadWIN_neon

// -----------------------------------------------------------------------------
// The CRT (Garner) over the three residues (each in [0, p)) of nd = 2·len digits (ntt_portable.cpp,
// arm64/NttNeon.s): v1 = x0, v2 = (x1 - v1)·p1^-1 mod p2, v3 = (x2 - v1 - v2·p1)·(p1p2)^-1 mod p3,
// the products by the constants by Shoup's method in 32 bits (q = hi(a·s), a·c - q·p in [0, 2p));
// the digit's value v1 + p1·v2 + p1p2·v3 (< 2^90, three digits) into the running sum (acc, four
// digits), two digits a word: the even one at digit 0, the odd one at digit 1; the low word out to
// r from its low end up, acc down a word. Returns the carry out of the top word.
// k (uint64 entries, the low halves read): p1 p2 p3 inv12 inv12s p1m3 p1m3s inv123 inv123s p1p2.
// r0 x0, r1 x1, r2 x2; stack: nd (+0), r (+8), len (+16), k (+24).
// Registers: r3 k, r4-r7 acc (digits 0-3), r8 r's end, r9 words left, r10-r12, lr scratch.
.equ C_P1, 0
.equ C_P2, 8
.equ C_P3, 16
.equ C_I12, 24
.equ C_I12S, 32
.equ C_P1M3, 40
.equ C_P1M3S, 48
.equ C_I123, 56
.equ C_I123S, 64
.equ C_P1P2, 72

// a·c mod p by Shoup (a in \a, c / s / p at k offsets) into \a, below p; r12, lr scratch
.macro SHOUP a, c, s, p
    ldr r12, [r3, #\s]
    umull lr, r12, \a, r12      // q = hi(a·s)
    ldr lr, [r3, #\c]
    mul \a, \a, lr              // a·c - q·p (mod 2^32)
    ldr lr, [r3, #\p]
    mls \a, r12, lr, \a
    cmp \a, lr
    subhs \a, \a, lr
.endm

// the next digit's value: v1 + p1·v2 + p1p2·v3 -> (r12 r11 r10), three digits; the residues from
// r0 / r1 / r2 (moved on); lr scratch
.macro CRT_VALUE
    ldr r10, [r0], #4           // v1
    ldr r11, [r1], #4           // x1
    ldr lr, [r3, #C_P2]
    cmp r10, lr                 // v1 mod p2
    movlo r12, r10
    subhs r12, r10, lr
    add r11, r11, lr
    sub r11, r11, r12           // d = x1 - v1 + p2 in (0, 2·p2)
    cmp r11, lr
    subhs r11, r11, lr
    SHOUP r11, C_I12, C_I12S, C_P2          // v2
    push {r10, r11}
    SHOUP r11, C_P1M3, C_P1M3S, C_P3        // v2·p1 mod p3
    ldr r12, [r2], #4           // x2
    ldr lr, [r3, #C_P3]
    cmp r10, lr                 // v1 mod p3
    subhs r10, r10, lr
    add r12, r12, lr, lsl #1
    sub r12, r12, r10
    sub r12, r12, r11           // t = x2 - v1 - v2·p1 + 2·p3 in (0, 3·p3)
    cmp r12, lr
    subhs r12, r12, lr
    cmp r12, lr
    subhs r12, r12, lr
    SHOUP r12, C_I123, C_I123S, C_P3        // v3 (r12 scratch inside: copied first)
    pop {r10, r11}
.endm
''')

# CRT_VALUE's SHOUP on r12 would clash with its scratch: the macro above takes the value in a
# register other than r12 / lr - fix it in the text: v3 goes through r11 (v2 saved on the stack).
txt = '\n'.join(out)
txt = txt.replace('''    SHOUP r12, C_I123, C_I123S, C_P3        // v3 (r12 scratch inside: copied first)
    pop {r10, r11}
.endm''', '''    mov r11, r12
    SHOUP r11, C_I123, C_I123S, C_P3        // v3
    mov r12, r11
    pop {r10, r11}              // v1 (as loaded), v2
.endm''')
out = [txt]

emit(r'''
ENTRY Fullint64NttCrtWIN_neon
    push {r4-r11, lr}
    ldr r3, [sp, #(36 + 24)]    // k
    ldr r8, [sp, #(36 + 8)]     // r
    ldr r9, [sp, #(36 + 16)]    // len
    add r8, r8, r9, lsl #3      // past r's end (its low word)
    mov r4, #0                  // acc
    mov r5, #0
    mov r6, #0
    mov r7, #0
    teq r9, #0
    beq 2f
1:  CRT_VALUE                   // digit 2w: v1 r10, v2 r11, v3 r12
    bl .Lcrt_value              // (r10 r11 r12) = its value, three digits
    adds r4, r4, r10
    adcs r5, r5, r11
    adcs r6, r6, r12
    adc r7, r7, #0
    CRT_VALUE                   // digit 2w + 1, one digit up
    bl .Lcrt_value
    adds r5, r5, r10
    adcs r6, r6, r11
    adc r7, r7, r12
    strd r4, r5, [r8, #-8]!     // the low word out
    mov r4, r6
    mov r5, r7
    mov r6, #0
    mov r7, #0
    subs r9, r9, #1
    bne 1b
2:  mov r0, r4                  // the carry out of the top word
    mov r1, r5
    pop {r4-r11, pc}

// (r10 v1, r11 v2, r12 v3) -> (r12 r11 r10) = v1 + p1·v2 + p1p2·v3; lr scratch, r0-r2 kept
.Lcrt_value:
    push {r0, r1, r2, lr}
    ldr r0, [r3, #C_P1]
    umull r1, r2, r0, r11       // p1·v2 (< 2^60)
    adds r1, r1, r10            // + v1
    adc r2, r2, #0
    ldr r0, [r3, #C_P1P2]       // p1p2 lo
    umull r10, lr, r0, r12      // p1p2·v3: lo·v3
    ldr r0, [r3, #(C_P1P2 + 4)] // p1p2 hi
    umull r11, r0, r0, r12      // hi·v3 (one digit up)
    adds r11, r11, lr
    adc r12, r0, #0             // (r12 r11 r10) = p1p2·v3
    adds r10, r10, r1
    adcs r11, r11, r2
    adc r12, r12, #0
    pop {r0, r1, r2, pc}
END Fullint64NttCrtWIN_neon
''')

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'Sources', 'arm32', 'NttNeon.s')
with open(path, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out))
print('written', os.path.normpath(path))
